import type { Insight } from "../../types/api";

const GLYPH = { positive: "▲", negative: "▼", neutral: "●" } as const;
const TONE = { positive: "text-gain", negative: "text-loss", neutral: "text-ink-3" } as const;
const TONE_LABEL = { positive: "Favourable", negative: "Unfavourable", neutral: "Observation" } as const;

export function Insights({ insights }: { insights: Insight[] }) {
  return (
    <div>
      <ol className="grid gap-px border-y border-line bg-line md:grid-cols-2">
        {insights.map((ins, i) => (
          <li key={ins.id} className="bg-paper py-8 md:px-8 md:[&:nth-child(odd)]:pl-0">
            <div className="flex items-start gap-4">
              <span className="num pt-1 text-[12px] text-ink-mute">{String(i + 1).padStart(2, "0")}</span>
              <div>
                <p className={`mb-2 flex items-center gap-1.5 text-[11px] font-semibold uppercase tracking-[0.14em] ${TONE[ins.tone]}`}>
                  <span aria-hidden="true" className="text-[9px]">{GLYPH[ins.tone]}</span>
                  {TONE_LABEL[ins.tone]}
                </p>
                <h4 className="text-xl font-semibold tracking-tight">{ins.title}</h4>
                <p className="mt-2 text-[15px] leading-relaxed text-ink-2">{ins.detail}</p>
              </div>
            </div>
          </li>
        ))}
      </ol>
      <p className="mt-6 max-w-2xl text-[13px] leading-relaxed text-ink-3">
        These observations are generated by fixed rules from the figures above. They describe what happened over the
        selected period; they are not forecasts, ratings or recommendations to buy or sell any security.
      </p>
    </div>
  );
}
